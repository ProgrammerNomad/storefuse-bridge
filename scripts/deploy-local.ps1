<#
.SYNOPSIS
  Mirror the development StoreFuse Bridge plugin into a local WordPress install.

.PARAMETER WordPressPath
  WordPress root (directory containing wp-load.php). When omitted, tries
  C:\xampp\htdocs\wordpress, D:\Websites\wordpress, then C:\xampp\htdocs.

.PARAMETER SiteUrl
  Store origin used for optional -RecordBaseline (default http://localhost).

.PARAMETER RecordBaseline
  After deploy, GET /status and append a snapshot to docs/BASELINE-RECORD.md.

.PARAMETER SkipBackup
  Do not copy the previous installed plugin to %TEMP% before replacing it.
#>
param(
    [string]$WordPressPath = '',
    [string]$SiteUrl = 'http://localhost',
    [switch]$RecordBaseline,
    [string]$BaselineFile = '',
    [switch]$SkipBackup
)

$ErrorActionPreference = 'Stop'

function Get-RelativePath {
    param(
        [string]$Base,
        [string]$Target
    )
    $baseUri = New-Object System.Uri(($Base.TrimEnd('\') + '\'))
    $targetUri = New-Object System.Uri($Target)
    return [System.Uri]::UnescapeDataString($baseUri.MakeRelativeUri($targetUri).ToString()).Replace('/', '\')
}

function Resolve-WordPressPath {
    param([string]$Candidate)
    if ($Candidate -ne '' -and (Test-Path -LiteralPath (Join-Path $Candidate 'wp-load.php'))) {
        return [IO.Path]::GetFullPath($Candidate)
    }
    foreach ($path in @(
            'C:\xampp\htdocs\wordpress',
            'D:\Websites\wordpress',
            'C:\xampp\htdocs'
        )) {
        if (Test-Path -LiteralPath (Join-Path $path 'wp-load.php')) {
            return [IO.Path]::GetFullPath($path)
        }
    }
    throw 'WordPress installation was not found. Pass -WordPressPath explicitly (directory with wp-load.php).'
}

function Get-SourceRevision {
    param([string]$Root)
    Push-Location $Root
    try {
        $hash = (git rev-parse --short HEAD 2>$null)
        if ($hash) { return $hash.Trim() }
    } finally {
        Pop-Location
    }
    return 'unknown'
}

$repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if ($WordPressPath -eq '') {
    $WordPressPath = Resolve-WordPressPath ''
} else {
    $WordPressPath = Resolve-WordPressPath $WordPressPath
}

$source = [IO.Path]::GetFullPath((Join-Path $repoRoot 'storefuse-bridge'))
$destination = [IO.Path]::GetFullPath((Join-Path $WordPressPath 'wp-content\plugins\storefuse-bridge'))

$criticalRelative = @(
    'storefuse-bridge.php',
    'includes\class-rest-schema.php',
    'includes\class-checkout-handoff.php',
    'includes\class-checkout-idempotency.php',
    'includes\class-cache.php',
    'includes\modules\class-module-status.php'
)

foreach ($rel in $criticalRelative) {
    if (-not (Test-Path -LiteralPath (Join-Path $source $rel))) {
        throw "Critical source file missing before deploy: $rel"
    }
}

$backup = $null
if (-not $SkipBackup -and (Test-Path -LiteralPath $destination)) {
    $backup = Join-Path $env:TEMP ('storefuse-installed-' + (Get-Date -Format 'yyyyMMdd-HHmmss'))
    Copy-Item -LiteralPath $destination -Destination $backup -Recurse
}

New-Item -ItemType Directory -Path $destination -Force | Out-Null

$excludeDirs = @('* - Copy', 'assets - Copy', 'admin - Copy')
if (Get-Command robocopy -ErrorAction SilentlyContinue) {
    $mirrorArgs = @($source, $destination, '/MIR', '/NFL', '/NDL', '/NJH', '/NJS', '/NC', '/NS', '/NP')
    foreach ($dir in $excludeDirs) {
        $mirrorArgs += '/XD'
        $mirrorArgs += $dir
    }
    $null = & robocopy @mirrorArgs
    if ($LASTEXITCODE -ge 8) {
        throw "robocopy failed with exit code $LASTEXITCODE"
    }
} else {
    if (Test-Path -LiteralPath $destination) {
        Get-ChildItem -LiteralPath $destination -Force | Remove-Item -Recurse -Force
    }
    Get-ChildItem -LiteralPath $source -Force | Where-Object {
        $_.Name -notmatch ' - Copy$'
    } | Copy-Item -Destination $destination -Recurse -Force
}

$revision = Get-SourceRevision -Root $repoRoot
$builtAt = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ss\Z')
$buildInfo = @"
<?php
/**
 * Generated by scripts/deploy-local.ps1 - do not edit in the installed copy.
 */
defined( 'ABSPATH' ) || exit;
define( 'STOREFUSE_BRIDGE_BUILD_ID', '$revision' );
define( 'STOREFUSE_BRIDGE_BUILD_TIME', '$builtAt' );

"@
$buildInfoPath = Join-Path $destination 'build-info.php'
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($buildInfoPath, $buildInfo, $utf8NoBom)

$mismatches = @()
foreach ($file in Get-ChildItem -LiteralPath $source -Recurse -File) {
    if ($file.FullName -match ' - Copy\\') { continue }
    $relative = Get-RelativePath -Base $source -Target $file.FullName
    if ($relative -eq 'build-info.php') {
        continue
    }
    $installed = Join-Path $destination $relative
    if (-not (Test-Path -LiteralPath $installed)) {
        $mismatches += "$relative (missing)"
        continue
    }
    if ((Get-FileHash -LiteralPath $file.FullName).Hash -ne (Get-FileHash -LiteralPath $installed).Hash) {
        $mismatches += $relative
    }
}
if ($mismatches.Count) {
    throw "Deployment verification failed: $($mismatches -join ', ')"
}

foreach ($rel in $criticalRelative) {
    if (-not (Test-Path -LiteralPath (Join-Path $destination $rel))) {
        throw "Critical file missing after deploy: $rel"
    }
}

Write-Output ''
Write-Output 'StoreFuse Bridge deployed.'
Write-Output "  Source:      $source"
Write-Output "  Destination: $destination"
Write-Output "  Build ID:    $revision ($builtAt)"
if ($backup) { Write-Output "  Backup:      $backup" }
Write-Output ''
Write-Output 'Record baseline:'
Write-Output "  curl -sS `"$($SiteUrl.TrimEnd('/'))/wp-json/storefuse/v1/status`""
Write-Output ''
Write-Output 'Optional fixtures (loopback only):'
Write-Output "  php scripts/local-fixtures.php `"$WordPressPath`" `"$env:TEMP\storefuse-fixtures`""

if ($RecordBaseline) {
    if ($BaselineFile -eq '') {
        $BaselineFile = [IO.Path]::GetFullPath((Join-Path $repoRoot 'docs\BASELINE-RECORD.md'))
    }
    $statusUrl = ($SiteUrl.TrimEnd('/') + '/wp-json/storefuse/v1/status')
    try {
        $response = Invoke-RestMethod -Uri $statusUrl -Method Get -TimeoutSec 30
        $data = $response.data
        $stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss K'
        $block = @(
            '',
            "## $stamp",
            '',
            '| Field | Value |',
            '|-------|-------|',
            "| WordPress path | ``$WordPressPath`` |",
            "| Site URL | ``$SiteUrl`` |",
            "| Bridge version | $($data.version) |",
            "| build_id | $($data.build_id) |",
            "| build_time | $($data.build_time) |",
            "| wordpress | $($data.wordpress) |",
            "| woocommerce | $($data.woocommerce) |",
            "| php | $($data.php) |",
            "| status | $($data.status) |",
            ''
        ) -join "`n"
        if (-not (Test-Path -LiteralPath $BaselineFile)) {
            Set-Content -LiteralPath $BaselineFile -Value "# Baseline records (auto-append)`n" -Encoding UTF8
        }
        Add-Content -LiteralPath $BaselineFile -Value $block -Encoding UTF8
        Write-Output "Baseline appended to $BaselineFile"
    } catch {
        Write-Warning "Deploy succeeded but GET /status baseline failed: $_"
        Write-Warning 'Start WordPress and curl /status, or re-run with -RecordBaseline.'
    }
}
